// Reads tokens/tokens.json (W3C DTCG-style) and generates:
//   src/styles/tokens.css — :root CSS custom properties
//   src/tokens.ts         — typed TS constants referencing the CSS vars
// Supports DTCG alias syntax: { "$value": "{color.palette.green-900}" }.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const source = JSON.parse(readFileSync(join(root, 'tokens', 'tokens.json'), 'utf8'));

const header = '// GENERATED by scripts/build-tokens.mjs — edit tokens/tokens.json instead.\n';
const cssHeader = '/* GENERATED by scripts/build-tokens.mjs — edit tokens/tokens.json instead. */\n';

/** @returns {Array<{path: string[], value: string}>} flat list of leaf tokens */
function flatten(node, path = []) {
  const out = [];
  for (const [key, val] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    if (val && typeof val === 'object' && '$value' in val) {
      out.push({ path: [...path, key], value: String(val.$value) });
    } else if (val && typeof val === 'object') {
      out.push(...flatten(val, [...path, key]));
    }
  }
  return out;
}

const flat = flatten(source);
const byPath = new Map(flat.map((t) => [t.path.join('.'), t.value]));

function resolve(value, seen = []) {
  const m = value.match(/^\{(.+)\}$/);
  if (!m) return value;
  const target = m[1];
  if (seen.includes(target)) throw new Error(`Circular token alias: ${[...seen, target].join(' -> ')}`);
  const next = byPath.get(target);
  if (next === undefined) throw new Error(`Unknown token alias: ${target}`);
  return resolve(next, [...seen, target]);
}

const varName = (path) => `--lc-${path.join('-')}`;

// --- CSS output -------------------------------------------------------------
const cssLines = flat.map(({ path, value }) => {
  const resolved = resolve(value);
  const comment = resolved !== value ? ` /* ${value} */` : '';
  return `  ${varName(path)}: ${resolved};${comment}`;
});
const css = `${cssHeader}:root {\n${cssLines.join('\n')}\n}\n`;

// --- TS output ---------------------------------------------------------------
// Nested object mirroring tokens.json structure; leaves are var(--lc-…) refs.
const tree = {};
for (const { path } of flat) {
  let node = tree;
  for (let i = 0; i < path.length - 1; i++) node = node[path[i]] ??= {};
  node[path[path.length - 1]] = `var(${varName(path)})`;
}
const toTs = (node, indent) => {
  const pad = '  '.repeat(indent);
  const lines = Object.entries(node).map(([k, v]) => {
    const key = /^[a-zA-Z_$][\w$]*$/.test(k) ? k : JSON.stringify(k);
    return typeof v === 'string' ? `${pad}${key}: ${JSON.stringify(v)},` : `${pad}${key}: {\n${toTs(v, indent + 1)}\n${pad}},`;
  });
  return lines.join('\n');
};
const ts = `${header}export const tokens = {\n${toTs(tree, 1)}\n} as const;\n\nexport type TokenValue = string;\n`;

mkdirSync(join(root, 'src', 'styles'), { recursive: true });
writeFileSync(join(root, 'src', 'styles', 'tokens.css'), css);
writeFileSync(join(root, 'src', 'tokens.ts'), ts);
console.log(`build-tokens: wrote ${flat.length} tokens -> src/styles/tokens.css + src/tokens.ts`);
